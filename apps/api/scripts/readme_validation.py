"""Copy the headline validation results from data/validation/report.md into README.md.

    python apps/api/scripts/readme_validation.py           # rewrite the README section
    python apps/api/scripts/readme_validation.py --check   # exit 1 if the README is out of date

Every number in the README's "Validation results" section is copied verbatim from report.md lines,
never retyped. tests/test_readme_validation.py fails when the two drift apart, for example after
validate.py --report-only regenerates the report.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
REPORT = REPO / "data" / "validation" / "report.md"
README = REPO / "README.md"
START = "<!-- validation:start: generated by apps/api/scripts/readme_validation.py from data/validation/report.md; do not edit by hand -->"
END = "<!-- validation:end -->"

# Rows of the report's "All items vs. review items excluded" table, by their first cell.
COMPARISON_ROWS = (
    "Usable answers (half A / half B)",
    "AUROC, 95% bootstrap CI (half B)",
    "ECE, 10 bins (half B)",
    "Brier (half B)",
    "High accuracy, all evaluated answers",
)


def _section(lines: list[str], heading: str) -> list[str]:
    start = lines.index(heading) + 1
    end = next((i for i in range(start, len(lines)) if lines[i].startswith("## ")), len(lines))
    return lines[start:end]


def _line_starting(lines: list[str], prefix: str) -> str:
    matches = [line for line in lines if line.startswith(prefix)]
    if len(matches) != 1:
        raise ValueError(f"expected one line starting with {prefix!r} in report.md, found {len(matches)}")
    return matches[0]


def _first_cell(row: str) -> str:
    return row.strip().strip("|").split("|")[0].strip()


def render(report_text: str) -> str:
    lines = report_text.splitlines()
    generated = _line_starting(lines, "Generated ")
    findings = [line for line in _section(lines, "## Key findings") if line[:3] in ("1. ", "2. ")]
    run = _section(lines, "## Run")
    comparison = _section(lines, "## All items vs. review items excluded")
    table = [line for line in comparison if line.startswith("|")]
    rows = {_first_cell(row): row for row in table[2:]}
    missing = [name for name in COMPARISON_ROWS if name not in rows]
    if missing or len(table) < 2:
        raise ValueError(f"report.md comparison table is missing rows: {missing}")
    costs = _section(lines, "## Latency and cost")
    block = [
        START,
        f"From [`data/validation/report.md`](data/validation/report.md) ({generated[0].lower()}{generated[1:].rstrip('.')})",
        "",
        _line_starting(run, "- Questions evaluated:"),
        _line_starting(run, "- Signal versions:"),
        _line_starting(run, "- Labels:"),
        "",
        *table[:2],
        *(rows[name] for name in COMPARISON_ROWS),
        "",
        _line_starting(costs, "- Signal latency:"),
        _line_starting(costs, "- Signal cost per answer:"),
        "",
        "The report's own reading of these numbers:",
        "",
        *(f"> {line}" for line in findings),
        "",
        "![Reliability diagram: observed accuracy against score, held-out half](data/validation/reliability_diagram.png)",
        END,
    ]
    return "\n".join(block)


def update(readme_text: str, block: str) -> str:
    start = readme_text.index(START)
    end = readme_text.index(END) + len(END)
    return readme_text[:start] + block + readme_text[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that README.md is up to date")
    args = parser.parse_args()
    readme = README.read_text(encoding="utf-8")
    updated = update(readme, render(REPORT.read_text(encoding="utf-8")))
    if args.check:
        if updated != readme:
            print("README.md validation section is out of date; run apps/api/scripts/readme_validation.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated, encoding="utf-8")
    print("README.md validation section updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
